def folk_short(k: str, sits: list[str]) -> str:
    first = sits[0].split(" — ", 1)
    second = sits[1].split(" — ", 1) if len(sits) > 1 else None
    a = first[1] if len(first) == 2 else k
    if second and len(second) == 2:
        return f"{first[0]} — {a}. {second[0]} — {second[1]}"
    return k


