def sits_lines(rows: list[tuple[str, str]]) -> list[str]:
    return [f"{a} — {b}" for a, b in rows if a and b]


def plain_short(text: str) -> str:
    """Оставить одну прямую строку, без «смотрите / спросите»."""
    cut = (
        ". Смотрите",
        ". Исход важнее",
        ". Запомните",
        ". Спросите",
        ". Не ставьте",
        ". Не вешайте",
    )
    s = text.strip()
    for sep in cut:
        idx = s.find(sep)
        if idx > 8:
            s = s[:idx].rstrip(" .,;:") + "."
            break
    return s


def prose_lines(text: str) -> list[str]:
    drop = (
        "не ставьте",
        "спросите",
        "не вешайте",
        "это зеркало",
        "это примета",
        "не делайте",
        "не судите",
        "не объявляйте",
        "не хороните",
        "не травите",
    )
    out: list[str] = []
    blob = text.replace("\n\n", "\n")
    for raw in blob.split("\n"):
        chunk = raw.strip()
        if not chunk:
            continue
        parts = []
        buf = ""
        for ch in chunk:
            buf += ch
            if ch in ".?!":
                parts.append(buf.strip())
                buf = ""
        if buf.strip():
            parts.append(buf.strip())
        for sent in parts:
            s = sent.strip()
            low = s.lower()
            if len(s) < 8 or any(d in low for d in drop):
                continue
            out.append(s.rstrip("."))
    return out[:6] or [text.strip().rstrip(".")]


def pack(
    u_short: str,
    u_rows: list[tuple[str, str]],
    f_short: str,
    f_rows: list[tuple[str, str]],
    i_short: str,
    i_rows: list[tuple[str, str]],
    l_short: str,
    l_long: str,
    a_short: str,
    a_long: str,
    u_intro: str = "",
    f_intro: str = "",
    i_intro: str = "",
) -> dict:
    del u_intro, f_intro, i_intro
    return {
        "universal": card(plain_short(u_short), "", sits_lines(u_rows)),
        "folk": card(plain_short(f_short), "", sits_lines(f_rows)),
        "islamic": card(plain_short(i_short), "", sits_lines(i_rows)),
        "love": card(plain_short(l_short), "", prose_lines(l_long)),
        "family": card(plain_short(a_short), "", prose_lines(a_long)),
    }


