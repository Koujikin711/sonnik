def seed_from_meta(meta: dict) -> dict:
    tid = meta["id"]
    block = TABIR[tid]
    return {
        "id": tid,
        "title": meta["title"],
        "letter": meta["letter"],
        "tags": meta["tags"],
        "aliases": meta.get("aliases", []),
        "related": meta.get("related", []),
        "traditions": {
            **block,
            "psychosomatic": {
                "short": meta["p_short"],
                "long": meta["p_long"],
                "hints": PSYCHO_HINTS,
            },
        },
    }


def apply_tabir(sym: dict) -> None:
    block = TABIR.get(sym["id"])
    if not block:
        return
    trad = sym.setdefault("traditions", {})
    for key in ("universal", "folk", "islamic", "love", "family"):
        if key in block:
            trad[key] = block[key]


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    by_id = {s["id"]: s for s in data["symbols"]}

    for meta in NEW_META:
        if meta["id"] not in by_id:
            data["symbols"].append(seed_from_meta(meta))
    by_id = {s["id"]: s for s in data["symbols"]}

    missing = [sid for sid in TABIR if sid not in by_id]
    if missing:
        raise SystemExit(f"TABIR without symbol: {missing}")

    for s in data["symbols"]:
        apply_tabir(s)
        aliases = [a for a in (s.get("aliases") or []) if a not in DROP_ALIASES.get(s["id"], set())]
        s["aliases"] = aliases

    for sid, block in CLEAR.items():
        if sid in by_id:
            apply_clear(by_id[sid], block)

    uncovered = [s["id"] for s in data["symbols"] if s["id"] not in TABIR and s["id"] not in CLEAR]
    if uncovered:
        print("WARN no tabir", uncovered)

    for t in data.get("traditions", []):
        if t.get("id") == "universal":
            t["title"] = "К чему снится"
        elif t.get("id") == "folk":
            t["title"] = "Народный"
        elif t.get("id") == "islamic":
            t["title"] = "Мусульманский"
        elif t.get("id") == "love":
            t["title"] = "Любовный"
        elif t.get("id") == "family":
            t["title"] = "Семейный"

    data["symbols"].sort(key=lambda s: (AZ.get(s["letter"], 99), s["title"]))
    SRC.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("symbols", len(data["symbols"]))
    print("tabir", len(TABIR), "clear", len(CLEAR), "new", len(NEW_META))


if __name__ == "__main__":
    main()

