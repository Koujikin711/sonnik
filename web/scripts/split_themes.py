def same_list(a: list[str], b: list[str]) -> bool:
    aa = [strip_prefix(x).lower() for x in a[:4]]
    bb = [strip_prefix(x).lower() for x in b[:4]]
    return bool(aa) and aa == bb


def lefts(hints: list[str]) -> list[str]:
    out: list[str] = []
    for h in hints[:4]:
        p = split_dash(h)
        out.append((p[0].lower() if p else strip_prefix(h).lower()))
    return out


def folk_short_from(hints: list[str], title: str) -> str:
    if len(hints) >= 2:
        return f"{hints[0].rstrip('.')}. {hints[1].rstrip('.')}"
    if hints:
        return hints[0].rstrip(".")
    return f"В народе {title.lower()} — своя примета"


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    changed = {"folk": 0, "love": 0, "family": 0}
    for s in data["symbols"]:
        tags = s.get("tags") or []
        trad = s["traditions"]
        u = trad.get("universal") or {}
        u_hints = list(u.get("hints") or [])
        for kind in ("folk", "love", "family"):
            cur = trad.get(kind) or {}
            old_hints = list(cur.get("hints") or [])
            # Свой сюжет (другие ситуации), не пересказ тех же четырёх строк.
            keep = kind != "folk" and old_hints and lefts(u_hints) != lefts(old_hints)
            if keep:
                continue
            new_hints = [layer_line(h, kind) for h in u_hints]
            for e in extras(kind, tags):
                if e not in new_hints:
                    new_hints.append(e)
            new_hints = new_hints[:8]
            if kind == "folk":
                cur["short"] = folk_short_from(new_hints, s["title"])
            elif not (cur.get("short") or "").strip():
                cur["short"] = (
                    f"В любви — к паре"
                    if kind == "love"
                    else f"В семье — к дому"
                )
            cur["long"] = ""
            cur["hints"] = new_hints
            trad[kind] = cur
            changed[kind] += 1

    SRC.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    vis = {"folk": 0, "love": 0, "family": 0, "cross": []}
    for s in data["symbols"]:
        t = s["traditions"]
        u = [strip_prefix(x).lower() for x in (t["universal"].get("hints") or [])][:4]
        for kind in ("folk", "love", "family"):
            o = [strip_prefix(x).lower() for x in (t[kind].get("hints") or [])][:4]
            if u and u == o:
                vis[kind] += 1
                if len(vis["cross"]) < 12:
                    vis["cross"].append(f"{s['title']}/{kind}")
        # raw visual without strip of «в паре»
        raw_u = [(x.strip().lower()) for x in (t["universal"].get("hints") or [])][:4]
        for kind in ("folk", "love", "family"):
            raw = [(x.strip().lower()) for x in (t[kind].get("hints") or [])][:4]
            if raw_u and raw_u == raw:
                vis["cross"].append(f"RAW {s['title']}/{kind}")
    print("rewrote", changed, "of", len(data["symbols"]))
    print("still_same_stripped", {k: vis[k] for k in ("folk", "love", "family")})
    print("samples", vis["cross"][:12])


if __name__ == "__main__":
    main()
