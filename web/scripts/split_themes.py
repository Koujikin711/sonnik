TRIPLE_SORTED = tuple(sorted(TRIPLE, key=lambda x: len(x[0]), reverse=True))


def strip_prefix(s: str) -> str:
    t = s.strip().rstrip(".")
    low = t.lower()
    for p in (
        "если увидит, что ",
        "если ",
        "примета: ",
        "в паре: ",
        "в доме: ",
        "в народе: ",
    ):
        if low.startswith(p):
            t = t[len(p) :]
            low = t.lower()
    return t


def apply_layer(text: str, idx: int) -> str:
    low = text.lower()
    for src, folk, love, fam in TRIPLE_SORTED:
        if src.lower() in low:
            return re.sub(re.escape(src), (folk, love, fam)[idx], text, count=1, flags=re.I)
    return text


def split_dash(raw: str) -> tuple[str, str] | None:
    t = strip_prefix(raw)
    if " — " not in t:
        return None
    left, right = t.split(" — ", 1)
    return left, right


def layer_line(raw: str, kind: str) -> str:
    idx = {"folk": 0, "love": 1, "family": 2}[kind]
    parts = split_dash(raw)
    if not parts:
        body = apply_layer(strip_prefix(raw), idx)
        if kind == "folk":
            return f"Примета: {body[0].lower() + body[1:] if body else body}.".replace("..", ".")
        if kind == "love":
            return f"В паре: {body}.".replace("..", ".")
        return f"В доме: {body}.".replace("..", ".")

    left, right = parts
    new_right = apply_layer(right, idx)
    if new_right.lower() == right.lower():
        if new_right.lower().startswith("к "):
            rest = new_right[2:]
            new_right = (
                f"{rest} у порога"
                if kind == "folk"
                else f"{rest} в паре"
                if kind == "love"
                else f"{rest} в доме"
            )
        else:
            tail = " у людей" if kind == "folk" else " вдвоём" if kind == "love" else " среди своих"
            if not new_right.lower().endswith(tail.strip()):
                new_right = new_right.rstrip(".") + tail
    left_l = left[0].lower() + left[1:] if left else left
    original = strip_prefix(raw).lower()
    line = f"{left} — {new_right}"
    if line.lower() == original:
        if kind == "folk":
            line = f"Примета: {left_l} — {new_right}"
        elif kind == "love":
            line = f"В паре: {left_l} — {new_right}"
        else:
            line = f"В доме: {left_l} — {new_right}"
    return line.rstrip(".") + "."


