def apply_clear(sym: dict, block: dict) -> None:
    for key in ("title", "letter", "tags", "aliases", "related"):
        if key in block:
            sym[key] = block[key]
    for trad in ("universal", "folk", "islamic", "love", "family"):
        if trad in block:
            sym.setdefault("traditions", {})[trad] = block[trad]
    # психосоматику в карточке сна не показываем — оставляем как есть, если была


def strip_boiler(sym: dict) -> None:
    isl = sym.get("traditions", {}).get("islamic")
    if not isl:
        return
    long = (isl.get("long") or "").replace(BOILER, "").strip()
    long = " ".join(long.split())
    if long in ("", "Образ читают по сюжету и жизни видевшего. Это смысл, не фетва."):
        short = isl.get("short") or ""
        long = f"{short} Смотрите, что вы делали и чем сон кончился."
    if CLOSER not in long:
        long = f"{long} {CLOSER}"
    isl["long"] = long


