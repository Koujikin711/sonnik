def apply_clear(sym: dict, block: dict) -> None:
    for key in ("title", "letter", "tags", "aliases", "related"):
        if key in block:
            sym[key] = block[key]
    for trad in ("universal", "folk", "islamic", "love", "family"):
        if trad in block:
            sym.setdefault("traditions", {})[trad] = block[trad]


def strip_boiler(sym: dict) -> None:
    isl = sym.get("traditions", {}).get("islamic")
    if not isl:
        return
    long = (isl.get("long") or "").replace(BOILER, "").strip()
    long = " ".join(long.split())
    if not long:
        isl["long"] = ""
        return
    if CLOSER not in long:
        long = f"{long} {CLOSER}"
    isl["long"] = long


def lion_seed() -> dict:
    return {
        "id": "lion",
        "title": "Лев",
        "letter": "Л",
        "tags": ["животные"],
        "aliases": ["львица", "львёнок"],
        "related": ["wolf", "bull", "snake"],
        "traditions": {},
    }


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    by_id = {s["id"]: s for s in data["symbols"]}
    if "lion" not in by_id:
        data["symbols"].append(lion_seed())
        by_id = {s["id"]: s for s in data["symbols"]}
    for sid, block in CLEAR.items():
        apply_clear(by_id[sid], block)
    for s in data["symbols"]:
        strip_boiler(s)
        if "lion" not in (s.get("related") or []) and s["id"] == "snake":
            rel = list(s.get("related") or [])
            if "lion" not in rel:
                rel.append("lion")
            s["related"] = rel
    order = {ch: i for i, ch in enumerate("АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ")}
    data["symbols"].sort(key=lambda s: (order.get(s["letter"], 99), s["title"]))
    SRC.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("symbols", len(data["symbols"]))
    print("lion", any(s["id"] == "lion" for s in data["symbols"]))


if __name__ == "__main__":
    main()
