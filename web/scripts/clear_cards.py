def card(short: str, long: str, hints: list[str]) -> dict:
    return {"short": short, "long": long.strip(), "hints": hints}


def i_card(short: str, long: str) -> dict:
    text = long.strip()
    if text and CLOSER not in text:
        text = f"{text}\n\n{CLOSER}"
    return card(short, text, HINTS_I)


