def pick(symbol_id: str, pool: tuple[str, ...]) -> str:
    h = int(hashlib.md5(symbol_id.encode()).hexdigest()[:8], 16)
    return pool[h % len(pool)]


def pick2(symbol_id: str, pool: tuple[str, ...], salt: str) -> str:
    h = int(hashlib.md5(f"{salt}:{symbol_id}".encode()).hexdigest()[:8], 16)
    return pool[h % len(pool)]


def omen_clause(short: str, fallback: str) -> str:
    first = short.strip().split(".")[0].strip()
    marked = list(re.finditer(r"(?:^|[—\-]\s*)(к\s+.+)$", first, flags=re.I))
    if marked:
        return marked[-1].group(1).strip(" .")
    if " — " in first:
        return first.split(" — ")[-1].strip(" .")
    if ":" in first:
        tail = first.split(":")[-1].strip(" .")
        if tail:
            return tail
    return fallback


def love_clause(short: str, title: str) -> str:
    return omen_clause(short, "к живому чувству")


def family_clause(short: str, title: str) -> str:
    return omen_clause(short, "к вести в доме")


def rewrite_love_family(data: dict) -> None:
    for symbol in data["symbols"]:
        aliases = [a for a in (symbol.get("aliases") or []) if not re.search(r"[A-Za-z]", a)]
        if aliases:
            symbol["aliases"] = aliases
        elif "aliases" in symbol:
            symbol["aliases"] = []

        title = symbol["title"]
        low = title.lower()
        traditions = symbol.get("traditions") or {}

        love = traditions.get("love")
        if love and love.get("short") and symbol["id"] != "sex":
            clause = love_clause(love["short"], title)
            extra = pick2(symbol["id"], EXTRAS, "x")
            frame = pick(symbol["id"], LOVE_FRAMES)
            love["short"] = frame.format(title=title, low=low, clause=clause, extra=extra)

        family = traditions.get("family")
        if family and family.get("short") and symbol["id"] != "sex":
            clause = family_clause(family["short"], title)
            frame = pick2(symbol["id"], FAMILY_FRAMES, "fam")
            family["short"] = frame.format(title=title, low=low, clause=clause)


def latin_visible(text: str) -> list[str]:
    return re.findall(r"[A-Za-z]{2,}", text)


def fix_body(data: dict) -> None:
    for item in data["items"]:
        patch = BODY_FIX.get(item["id"])
        if not patch:
            continue
        for key, value in patch.items():
            item[key] = value
        if not item.get("findings"):
            item["findings"] = []


def main() -> None:
    body = json.loads(BODY.read_text(encoding="utf-8"))
    fix_body(body)
    BODY.write_text(json.dumps(body, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    left = []
    for item in body["items"]:
        blob = " ".join(
            [
                item.get("title", ""),
                item.get("short", ""),
                item.get("long", ""),
                item.get("term", ""),
                item.get("doctor", ""),
                *item.get("aliases", []),
                *item.get("hints", []),
                *item.get("causes", []),
                *item.get("findings", []),
            ]
        )
        hits = latin_visible(blob)
        if hits:
            left.append((item["id"], hits))
    print("body latin", left or "none")

    syms = json.loads(SYMS.read_text(encoding="utf-8"))
    rewrite_love_family(syms)
    SYMS.write_text(json.dumps(syms, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    slat = []
    opens = {}
    for s in syms["symbols"]:
        for a in s.get("aliases") or []:
            if latin_visible(a):
                slat.append(("alias", s["id"], a))
        for tid, block in (s.get("traditions") or {}).items():
            for key in ("short", "long"):
                v = block.get(key) or ""
                if latin_visible(v):
                    slat.append((f"{tid}.{key}", s["id"], v[:80]))
            for h in block.get("hints") or []:
                if latin_visible(h):
                    slat.append((f"{tid}.hint", s["id"], h[:80]))
        love = (s.get("traditions") or {}).get("love") or {}
        short = (love.get("short") or "").strip()
        pref = " ".join(short.split()[:3])
        opens[pref] = opens.get(pref, 0) + 1
    print("symbol latin", slat or "none")
    print("love unique 3-word prefixes", len(opens), "max", max(opens.values()) if opens else 0)


if __name__ == "__main__":
    main()
