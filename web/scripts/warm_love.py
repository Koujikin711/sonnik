def first_line(short: str) -> str:
    parts = [p.strip() for p in re.split(r"(?<=\.)\s+", short) if p.strip()]
    if not parts:
        return short.strip()
    if len(parts) > 1 and any(parts[-1].startswith(x) for x in OLD_EXTRAS):
        return parts[0]
    return parts[0]


def clause_of(line: str) -> str:
    if " — " in line:
        return line.split(" — ", 1)[1].rstrip(".")
    return line.rstrip(".")


def pick_extra(symbol_id: str) -> str:
    h = hashlib.md5(symbol_id.encode()).hexdigest()
    return POOL[int(h[:8], 16) % len(POOL)]


def warm_short(symbol_id: str, title: str, short: str) -> str:
    if symbol_id == "sex":
        return short.strip()
    line = first_line(short).rstrip(".")
    clause = clause_of(line)
    extra = pick_extra(symbol_id)
    return f"Когда снится {title.lower()}, любовь видит так: {clause}. {extra}"


def warm_hint(raw: str, title: str) -> str:
    t = raw.strip().rstrip(".")
    t = re.sub(r"^Если\s+", "", t)
    t = re.sub(rf"^{re.escape(title.lower())}\s+", "", t, flags=re.I)
    if " — " not in t:
        return (t[:1].upper() + t[1:] if t else t) + "."
    left, right = t.split(" — ", 1)
    key = right.strip()
    if not key.endswith("."):
        key += "."
    mapped = RIGHT.get(key) or RIGHT.get(right.strip() + ".")
    if not mapped:
        mapped = re.sub(r"\s*в паре\.?$", "", right.strip())
        mapped = re.sub(r"^к\s+", "", mapped).rstrip(".")
    left = left[0].upper() + left[1:] if left else left
    return f"{left} — {mapped}."


def main() -> None:
    data = json.loads(PATH.read_text(encoding="utf-8"))
    for symbol in data["symbols"]:
        love = symbol.get("traditions", {}).get("love")
        if not love:
            continue
        short = (love.get("short") or "").strip()
        if short:
            love["short"] = warm_short(symbol["id"], symbol["title"], short)
        love["hints"] = [warm_hint(h, symbol["title"]) for h in (love.get("hints") or [])]
        symbol["traditions"]["love"] = love
    PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("warmed love", len(data["symbols"]))


if __name__ == "__main__":
    main()
