def build_new(seed: dict) -> dict:
    return {
        "id": seed["id"],
        "title": seed["title"],
        "letter": letter_of(seed["title"]),
        "tags": seed["tags"],
        "aliases": seed.get("aliases") or [],
        "related": [r for r in (seed.get("related") or [])],
        "traditions": {
            "universal": meaning_from_seed(seed, "universal", 0),
            "folk": meaning_from_seed(seed, "folk", 1),
            "islamic": meaning_from_seed(seed, "islamic", 2),
            "psychosomatic": psychosomatic(seed["title"]),
            "love": meaning_from_seed(seed, "love", 3),
            "family": meaning_from_seed(seed, "family", 4),
        },
    }


def sort_key(symbol: dict) -> tuple:
    az = "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"
    letter = symbol["letter"]
    return (az.find(letter) if letter in az else 99, symbol["title"])


def run() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    have = {s["id"] for s in data["symbols"]}

    for symbol in data["symbols"]:
        title = symbol["title"]
        universal_short = (symbol["traditions"].get("universal") or {}).get("short") or ""
        for tab in TABS:
            entry = symbol["traditions"].get(tab)
            if not entry:
                continue
            symbol["traditions"][tab] = rebuild_entry(title, tab, entry, universal_short)

    seeds = NEW + more_new()
    _fix_queue(seeds)
    seeds = seeds + MORE2 + MORE3
    added = 0
    for seed in seeds:
        if seed["id"] in have:
            continue
        # drop related that do not exist yet (except other new ids)
        new_ids = {s["id"] for s in seeds}
        seed["related"] = [r for r in seed.get("related") or [] if r in have or r in new_ids]
        data["symbols"].append(build_new(seed))
        have.add(seed["id"])
        added += 1

    data["symbols"].sort(key=sort_key)
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    SRC.write_text(text, encoding="utf-8")
    COPY.write_text(text, encoding="utf-8")

    from collections import Counter
    fam = Counter(s["traditions"]["family"]["short"].split(".")[0] for s in data["symbols"])
    folk = Counter(s["traditions"]["folk"]["short"].split(".")[0] for s in data["symbols"])
    print("symbols", len(data["symbols"]), "added", added)
    print("family first unique", len(fam), "top", fam.most_common(3))
    print("folk first unique", len(folk), "top", folk.most_common(3))
    for sid in ("silver", "tsunami", "hijab", "firing", "hug", "eagle"):
        s = next(x for x in data["symbols"] if x["id"] == sid)
        print("\n", s["title"], "U:", s["traditions"]["universal"]["short"])
        print(" I:", s["traditions"]["islamic"]["short"])
        print(" A:", s["traditions"]["family"]["short"])


if __name__ == "__main__":
    run()
