def gender(title: str) -> str:
    t = title.lower()
    if t in PLURAL:
        return "pl"
    if t in NEUTER or t.endswith(("ться", "тись", "чь")):
        return "n"
    if t in FEM_SOFT:
        return "f"
    if t in MASC_SOFT:
        return "m"
    if t.endswith(("а", "я")):
        return "f"
    if t.endswith(("о", "е", "ё")):
        return "n"
    if t.endswith(("ы", "и")):
        return "pl"
    return "m"


def is_verb(title: str) -> bool:
    return title.lower().endswith(("ться", "тись", "чь", "ти"))


def pick(key: str, items: list[str]) -> str:
    h = int(hashlib.sha1(key.encode("utf-8")).hexdigest(), 16)
    return items[h % len(items)]


def cap(text: str) -> str:
    text = text.strip()
    return text[0].upper() + text[1:] if text else text


def end_dot(text: str) -> str:
    text = re.sub(r"\s+", " ", text).strip().rstrip(" .;")
    return f"{text}." if text else ""


def hint_key(raw: str) -> str:
    t = raw.strip()
    t = re.sub(r"^если увидит,\s*что\s+", "", t, flags=re.I)
    t = re.sub(r"^если увидит,\s+", "", t, flags=re.I)
    t = re.sub(r"^если увидит\s+", "", t, flags=re.I)
    t = re.sub(r"^если\s+", "", t, flags=re.I)
    dash = t.find(" — ")
    left = (t[:dash] if dash > 0 else t).lower()
    return re.sub(r"\s+", " ", left).strip()


def is_generic(raw: str) -> bool:
    return hint_key(raw) + "." in GENERIC or raw.strip().lower() in GENERIC


def clean_list(items: list[str]) -> list[str]:
    out: list[str] = []
    seen: set[str] = set()
    for raw in items:
        if is_generic(raw):
            continue
        line = end_dot(raw)
        line = line.replace("своё ли образ", "свой ли образ")
        line = line.replace("своя ли образ", "свой ли образ")
        line = line.replace("вещь свой и целый", "вещь своя и целая")
        line = line.replace("вещь своё и целое", "вещь своя и целая")
        key = hint_key(line)
        if not key or key in seen:
            continue
        seen.add(key)
        out.append(line)
    return out


def omen_of(short: str, title: str) -> str:
    first = short.split(".")[0]
    if " — " in first:
        right = first.split(" — ", 1)[1].strip()
        right = re.sub(rf"^{re.escape(title)}\s*", "", right, flags=re.I)
        return right.rstrip(".")
    t = re.sub(rf"^{re.escape(title)}\s*[—–-]\s*", "", first, flags=re.I)
    t = re.sub(r"^это\s+", "", t, flags=re.I)
    return t.rstrip(".")


def join3(parts: list[str]) -> str:
    rows: list[str] = []
    for p in parts:
        t = end_dot(p)
        if t and t not in rows:
            rows.append(t)
        if len(rows) >= 3:
            break
    return " ".join(rows)


