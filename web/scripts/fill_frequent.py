def letter_of(title: str) -> str:
    ch = title[0].upper()
    return "Е" if ch == "Ё" else ch


def meaning_from_seed(seed: dict, tab: str, idx: int) -> dict:
    core = seed[{"universal": "u", "folk": "f", "islamic": "i", "love": "l", "family": "a"}[tab]]
    sits = seed["sits"]
    hints = [end_dot(f"Если {left} — {row[idx]}") for left, *row in sits]
    bits = [f"{left.capitalize()} — {row[idx]}" for left, *row in sits]
    short = join3([core, *bits[:2]])
    long = join3([*bits[2:5], pick(seed["id"] + tab + "c", CLOSERS)])
    return {"short": short, "long": long, "hints": hints}


