def fill_hints(title: str, tab: str, hints: list[str]) -> list[str]:
    out = clean_list(hints)
    seen = {hint_key(h) for h in out}
    for raw in titled_hints(title, tab):
        line = end_dot(raw)
        key = hint_key(line)
        if not key or key in seen:
            continue
        seen.add(key)
        out.append(line)
        if len(out) >= 7:
            break
    return out[:7]


def rebuild_entry(title: str, tab: str, entry: dict, universal_short: str) -> dict:
    hints = fill_hints(title, tab, list(entry.get("hints") or []))
    short = entry.get("short") or ""
    omen = omen_of(universal_short, title)
    low = title.lower()
    bits = []
    for h in hints:
        t = re.sub(r"^если\s+", "", h, flags=re.I).strip()
        bits.append(cap(t))

    if tab == "family":
        lead = pick(title + "fam", FAMILY_LEAD).format(t=title, omen=omen)
        short = join3([lead, *bits[:2]])
        long = join3([*bits[2:5], pick(title + "faml", CLOSERS)])
    elif tab == "folk":
        lead = pick(title + "folk", FOLK_LEAD).format(t=low, omen=omen)
        short = join3([lead, *bits[:2]])
        long = join3([*bits[2:5], pick(title + "folkl", CLOSERS)])
    elif tab == "islamic":
        first = short.split(".")[0]
        if not first.lower().startswith("это"):
            first = f"Это {omen[0].lower() + omen[1:] if omen else low}"
        second = bits[0] if bits else f"{title} ясный и свой — польза ближе к этому образу"
        third = bits[1] if len(bits) > 1 else "Порченый вид — вред уже виден на нём"
        short = join3([first, second, third])
        long = join3([*bits[2:5], pick(title + "isl", [
            "Сон сам по себе не вердикт: смотрят состояние видевшего.",
            "Пугающий сон не разносят; спокойный можно держать как весть.",
            "Один образ у двух людей читается по-разному.",
        ])])
    elif tab == "love":
        # Keep unique existing opener, drop generic tail if any.
        sentences = [s.strip() for s in re.split(r"(?<=\.)\s+", short) if s.strip()]
        keep = []
        for s in sentences:
            if is_generic(s):
                continue
            keep.append(s)
        if bits:
            keep.append(bits[0])
        short = join3(keep[:3] if keep else [short, *bits[:2]])
        long = join3([*bits[1:4], pick(title + "lovel", [
            "Пара читается по теплу, а не по победе в сцене.",
            "Чужая близость во сне чаще к ревности, чем к новому союзу.",
            "Если делили поровну — лад ещё держится.",
        ])])
    else:
        first = short.split(".")[0]
        short = join3([first, *bits[:2]])
        long = join3([*bits[2:5], pick(title + "ul", CLOSERS)])

    return {"short": short, "long": long, "hints": hints}


