def clean_aliases(aliases: list[str] | None) -> list[str]:
    out = []
    for a in aliases or []:
        if MED_ALIAS.search(a):
            continue
        if re.search(r"[A-Za-z]", a):
            continue
        out.append(a)
    return out


def run() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    data["disclaimer"] = ""
    missing = []
    for item in data["items"]:
        psy = PSY.get(item["id"])
        if not psy:
            missing.append(item["id"])
            continue
        item["term"] = psy["term"]
        item["short"] = psy["short"]
        item["long"] = psy["long"]
        item["causes"] = list(psy["feel"])
        item["findings"] = list(psy["body"])
        item["hints"] = list(psy["look"])
        item["doctor"] = ""
        item["aliases"] = clean_aliases(item.get("aliases"))
    if missing:
        raise SystemExit(f"no psy for {missing}")
    # catch leftover latin in new texts
    blob_bad = []
    for item in data["items"]:
        blob = " ".join(
            [
                item["term"],
                item["short"],
                item["long"],
                *item["causes"],
                *item["findings"],
                *item["hints"],
            ]
        )
        if re.search(r"[A-Za-z]{2,}|%|20\d\d|врач|исследован|диагноз|рефлекс", blob, re.I):
            blob_bad.append((item["id"], blob[:160]))
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    SRC.write_text(text, encoding="utf-8")
    COPY.write_text(text, encoding="utf-8")
    print("items", len(data["items"]), "bad", blob_bad)
    for sid in ("pinch-self", "tongue", "lump-throat"):
        i = next(x for x in data["items"] if x["id"] == sid)
        print("\n", i["title"])
        print(i["term"])
        print(i["short"])


if __name__ == "__main__":
    run()
