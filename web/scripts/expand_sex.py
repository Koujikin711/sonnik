OPEN = (
    "«{title}» для двоих — {clause}. {extra}",
    "{title} про любовь говорит так: {clause}. {extra}",
    "Образ «{title}» в паре — {clause}. {extra}",
    "Если во сне {low} — сердце читает: {clause}. {extra}",
    "Сон о «{title}» для любви — {clause}. {extra}",
    "Чувство через «{low}»: {clause}. {extra}",
    "{title} снится — и между вами это: {clause}. {extra}",
    "Не примета на удачу: «{title}» в любви — {clause}. {extra}",
)


def parse_love(short: str, title: str) -> tuple[str, str]:
    s = short.strip()
    m = re.search(r"любовь видит так:\s*(.+?)\.\s*(.+)$", s)
    if m:
        return m.group(1).rstrip("."), m.group(2).strip()
    if " — " in s.split(".")[0]:
        first = s.split(".")[0]
        clause = first.split(" — ", 1)[1].strip()
        rest = s[len(first) :].lstrip(". ").strip()
        return clause.rstrip("."), rest
    return s, ""


def rewrite_love_openers(data: dict) -> None:
    for symbol in data["symbols"]:
        if symbol["id"] == "sex":
            continue
        love = symbol.get("traditions", {}).get("love")
        if not love or not love.get("short"):
            continue
        clause, extra = parse_love(love["short"], symbol["title"])
        if not extra:
            extra = "Пусть это будет живым, не позой."
        h = int(hashlib.md5(symbol["id"].encode()).hexdigest()[:8], 16)
        frame = OPEN[h % len(OPEN)]
        love["short"] = frame.format(
            title=symbol["title"],
            low=symbol["title"].lower(),
            clause=clause,
            extra=extra,
        )


def main() -> None:
    data = json.loads(PATH.read_text(encoding="utf-8"))
    sex = next(s for s in data["symbols"] if s["id"] == "sex")
    sex["aliases"] = ["секс", "интим", "близость во сне", "постель с кем-то"]
    for key, block in SEX.items():
        sex["traditions"][key] = block
    rewrite_love_openers(data)
    PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("sex expanded; love openers varied")


if __name__ == "__main__":
    main()
