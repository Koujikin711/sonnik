def main() -> None:
    src = json.loads(SRC.read_text(encoding="utf-8"))
    symbols = [expand_one(s) for s in src["symbols"]]
    catalog = {
        "version": 2,
        "disclaimer": (
            "Тексты — свои формулировки на основе общих традиций (народная примета, "
            "исламский та‘бир, психосоматика как разговор тела и чувства). "
            "Это не дословная выгрузка чужих сонников, не медицинский диагноз и не фетва."
        ),
        "traditions": [
            {"id": "universal", "title": "Универсальный", "group": "predictive"},
            {"id": "folk", "title": "Народный", "group": "predictive"},
            {"id": "islamic", "title": "Мусульманский", "group": "religious"},
            {"id": "psychosomatic", "title": "Психосоматика", "group": "psycho"},
            {"id": "love", "title": "Любовный", "group": "theme"},
            {"id": "family", "title": "Семейный", "group": "theme"},
        ],
        "symbols": symbols,
    }
    SRC.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    longs = []
    for s in symbols:
        for k, v in s["traditions"].items():
            longs.append((k, len(v["long"])))
    from collections import defaultdict

    acc: dict[str, list[int]] = defaultdict(list)
    for k, n in longs:
        acc[k].append(n)
    print("symbols", len(symbols))
    for k, arr in acc.items():
        print(f"{k}: avg long {sum(arr)//len(arr)} chars, n={len(arr)}")


