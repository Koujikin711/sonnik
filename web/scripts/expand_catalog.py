def hints_for(kind: str, title: str, tags: list[str], note: dict) -> list[str]:
    if kind == "universal":
        return [
            f"Запомните состояние {title.lower()} — спокойное, приятное или пугающее.",
            "Один символ без сюжета и чувства почти ничего не значит.",
            "Повтор сна важнее разовой картинки.",
        ]
    if kind == "folk":
        return [
            "В приметах детали решают: цвет, целое/битое, своё/чужое.",
            "Народная примета — про исход дня, не про судьбу на годы.",
            f"Свяжите {title.lower()} с тем, что уже зреет в быту.",
        ]
    if kind == "islamic":
        return [
            f"Смысл «{title.lower()}» зависит от действия, чувства и исхода, не от ярлыка.",
            "Детали (чистое/мутное, своё/чужое, чем кончилось) важнее названия.",
            "Это предположение о смысле сна, не фетва и не приговор.",
        ]
    if kind == "psychosomatic":
        body = note.get("body", "общее напряжение")
        return [
            f"Какое место в теле отозвалось: {body}.",
            "Сон не ставит диагноз и не заменяет врача.",
            "Спросите, какую эмоцию вы не доживаете днём.",
        ]
    if kind == "love":
        return [
            "Кто рядом с символом — вы, партнёр или третий?",
            "Тепло во сне и холод после пробуждения — разные сигналы.",
        ]
    return [
        "Кто в семье был в кадре и кто «за кадром».",
        "Дом, стол и дети во сне часто про роли, не про прогноз.",
    ]


def sentences(*parts: str) -> str:
    text = " ".join(p.strip() for p in parts if p and p.strip())
    return text.replace("  ", " ").strip()


