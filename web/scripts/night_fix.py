def clean_folk_line(h: str, orig_u: str | None) -> str:
    t = h.strip().rstrip(".")
    t = re.sub(r" у людей$", "", t)
    t = re.sub(r" у порога$", "", t)
    t = t.strip()
    if orig_u and strip_prefix(t).lower() == strip_prefix(orig_u).lower():
        parts = t.split(" — ", 1)
        if len(parts) == 2 and "во дворе" not in parts[0].lower():
            return f"{parts[0]} во дворе — {parts[1]}."
    if not t.endswith("."):
        t += "."
    return t


def voice_line(h: str, kind: str) -> str:
    raw = strip_prefix(h)
    return layer_line(raw if " — " in raw else h, kind)


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    stats = {"who": 0, "pack": 0, "folk": 0, "twins": 0}

    for s in data["symbols"]:
        trad = s["traditions"]
        tags = s.get("tags") or []
        u_hints = list((trad["universal"].get("hints") or []))
        folk = trad["folk"]
        love = trad["love"]
        fam = trad["family"]
        islam = trad["islamic"]

        # 1) народ: убрать хвосты «у людей / у порога»
        new_folk = []
        for i, h in enumerate(folk.get("hints") or []):
            src = u_hints[i] if i < len(u_hints) else None
            nh = clean_folk_line(h, src)
            new_folk.append(nh)
            if nh != h:
                stats["folk"] += 1
        for e in extras("folk", tags):
            e = clean_folk_line(e, None)
            if e not in new_folk:
                new_folk.append(e)
        seen: set[str] = set()
        dedup: list[str] = []
        for h in new_folk:
            key = h.strip().lower()
            if key in seen:
                continue
            seen.add(key)
            dedup.append(h)
        folk["hints"] = dedup[:8]
        if new_folk:
            folk["short"] = f"{new_folk[0].rstrip('.')}. {new_folk[1].rstrip('.')}" if len(new_folk) > 1 else new_folk[0]

        # 2) любовь ≠ семья
        lh = list(love.get("hints") or [])
        fh = list(fam.get("hints") or [])
        if [x.strip().lower() for x in lh] == [x.strip().lower() for x in fh] and lh:
            love["hints"] = ([voice_line(h, "love") for h in u_hints] + extras("love", tags))[:8]
            fam["hints"] = ([voice_line(h, "family") for h in u_hints] + extras("family", tags))[:8]
            stats["twins"] += 1

        # 3) исламский «это кто»
        who = WHO.get(s["id"])
        if who and islam.get("short") != who:
            islam["short"] = who
            stats["who"] += 1
        elif not (islam.get("short") or "").startswith("Это "):
            islam["short"] = who or "Это образ дела"

        # 4) усилить цепочку, если есть свой пакет и нет золотого списка
        if s["id"] in PACK and s["id"] not in KEEP_I:
            islam["hints"] = PACK[s["id"]]
            islam["long"] = ""
            stats["pack"] += 1
        elif s["id"] in PACK and s["id"] in {"gold", "key", "bracelet", "well", "palace", "dates", "bull"}:
            # у этих хадис есть, но список был шаблонный
            islam["hints"] = PACK[s["id"]]
            islam["long"] = ""
            stats["pack"] += 1

        trad["folk"] = folk
        trad["love"] = love
        trad["family"] = fam
        trad["islamic"] = islam

    SRC.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    # проверка
    twins = folk_tail = k_islam = 0
    for s in data["symbols"]:
        t = s["traditions"]
        if [x.lower() for x in (t["love"].get("hints") or [])] == [x.lower() for x in (t["family"].get("hints") or [])]:
            twins += 1
        for h in t["folk"].get("hints") or []:
            if h.endswith(" у людей.") or " у порога." in h:
                folk_tail += 1
        for h in t["islamic"].get("hints") or []:
            if re.search(r"— к [а-яё]", h, re.I) and s["id"] not in KEEP_I:
                k_islam += 1
    print("stats", stats, "symbols", len(data["symbols"]))
    print("left twins", twins, "folk tails", folk_tail, "islam k leftover", k_islam)


if __name__ == "__main__":
    main()
