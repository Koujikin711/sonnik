def who_from(k: str) -> str:
    t = k.strip()
    if t.startswith("Это "):
        return t.rstrip(".")
    if t.startswith("к "):
        return f"Это знак {t}"
    return f"Это {t}"


def as_esli(line: str) -> str:
    s = line.strip().rstrip(".")
    if s.lower().startswith("если "):
        return s
    return f"Если {s[0].lower() + s[1:]}" if s else s


