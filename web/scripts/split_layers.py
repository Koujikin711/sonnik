REPL_SORTED = tuple(sorted(REPL, key=lambda x: len(x[0]), reverse=True))


def strip_esli(s: str) -> str:
    t = s.strip().rstrip(".")
    low = t.lower()
    if low.startswith("если увидит, что "):
        t = t[17:]
    elif low.startswith("если "):
        t = t[5:]
    return t


def apply_repl(t: str) -> str:
    for a, b in REPL_SORTED:
        t = re.sub(re.escape(a), b, t, flags=re.I)
    return t


def tabir_line(raw: str) -> str:
    original = strip_esli(raw)
    t = apply_repl(original)
    if " — " in t:
        left, right = t.split(" — ", 1)
        right = apply_repl(right)
        if right.lower().startswith("к "):
            right = right[2:]
        left_l = left[0].lower() + left[1:] if left else left
        out = f"Если увидит, что {left_l} — {right}"
    else:
        body = t[0].lower() + t[1:] if t else t
        out = f"Если увидит, что {body}"
    return out.rstrip(".") + "."


def who_for(sym: dict, islam_short: str) -> str:
    s = (islam_short or "").strip().rstrip(".")
    if s.startswith("Это ") and "знак к " not in s.lower() and "знак:" not in s.lower():
        return s
    tags = list(sym.get("tags") or [])
    for tag in TAG_ORDER:
        if tag in tags:
            return f"Это {WHO_TAG[tag]}"
    k = (sym.get("traditions", {}).get("universal", {}).get("short") or "")
    if " — " in k:
        right = apply_repl(k.split(" — ", 1)[1])
        if right.lower().startswith("к "):
            right = right[2:]
        return f"Это {right}"
    return "Это образ дела"


