def main() -> None:
    data = json.loads(SYM.read_text(encoding="utf-8"))
    if not any(s["id"] == "sex" for s in data["symbols"]):
        data["symbols"].append(SEX)
        for sid in ("intimacy", "kiss", "bed", "wedding"):
            for s in data["symbols"]:
                if s["id"] == sid:
                    rel = list(s.get("related") or [])
                    if "sex" not in rel:
                        rel.append("sex")
                    s["related"] = rel
        data["symbols"].sort(key=lambda s: az_key(s["letter"], s["title"]))
    SYM.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    body = json.loads(BODY.read_text(encoding="utf-8"))
    if not any(i["id"] == "tongue" for i in body["items"]):
        body["items"].append(TONGUE)
    BODY.write_text(json.dumps(body, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("sex and tongue added; words", len(data["symbols"]), "body", len(body["items"]))


if __name__ == "__main__":
    main()
