def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    missing = []
    for item in data["items"]:
        sci = SCIENCE.get(item["id"])
        if not sci:
            missing.append(item["id"])
            continue
        item["short"] = sci["short"]
        item["long"] = sci["long"]
        item["hints"] = sci["hints"]
        item["term"] = sci["term"]
        item["causes"] = sci["causes"]
        item["findings"] = sci["findings"]
        item["doctor"] = sci["doctor"]
        item["sources"] = [S[k] for k in sci["sources"]]
        aliases = item.get("aliases") or []
        term = sci["term"].split("(")[0].strip()
        if term.lower() not in " ".join(aliases).lower() and term not in item["title"]:
            aliases = aliases + [term]
        item["aliases"] = aliases
    if missing:
        raise SystemExit(f"no science block for: {missing}")
    data["disclaimer"] = (
        "Тексты раздела «Тело» — краткие справки по опубликованным обзорам, не диагноз и не план лечения. "
        "Номера и ссылки — на найденные статьи. Если боль, одышка, кровь, паника или симптом сильны — к врачу."
    )
    SRC.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"updated {len(data['items'])} body items")


if __name__ == "__main__":
    main()
